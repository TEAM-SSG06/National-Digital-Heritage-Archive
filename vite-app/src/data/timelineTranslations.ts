export function getLocalizedMilestone<
  T extends {
    id: string
    title: string
    date: string
    location: string
    eraLabel: string
    category: string
    description: string
    quote?: string
    impact?: string
  },
>(milestone: T, lang: string): T {
  if (lang === "english") return milestone
  const langKey = lang as "hindi" | "marathi" | "tamil"
  const localized = TIMELINE_LOCALIZATIONS[langKey]?.[milestone.id]
  if (!localized) return milestone

  return {
    ...milestone,
    title: localized.title || milestone.title,
    date: localized.date || milestone.date,
    location: localized.location || milestone.location,
    eraLabel: localized.eraLabel || milestone.eraLabel,
    category: localized.category || milestone.category,
    description: localized.description || milestone.description,
    quote: localized.quote || milestone.quote,
    impact: localized.impact || milestone.impact,
  }
}

